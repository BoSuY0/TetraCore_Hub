// Provider defines the interface for secret storage providers.
type Provider interface {
	// Get retrieves a secret by key.
	Get(ctx context.Context, key string) (string, error)
	// Set stores a secret.
	Set(ctx context.Context, key, value string) error
	// Delete removes a secret.
	Delete(ctx context.Context, key string) error
	// List returns all secret keys.
	List(ctx context.Context) ([]string, error)
	// Name returns the provider name.
	Name() string
}

// ============================================================
// EnvFileProvider - Local .env file provider (for development)
// ============================================================

// EnvFileProvider manages secrets in a .env file.
type EnvFileProvider struct {
	filePath string
	secrets  map[string]string
}

// NewEnvFileProvider creates a new EnvFileProvider.
func NewEnvFileProvider(filePath string) (*EnvFileProvider, error) {
	p := &EnvFileProvider{
		filePath: filePath,
		secrets:  make(map[string]string),
	}

	if err := p.load(); err != nil {
		return nil, err
	}

	return p, nil
}

func (p *EnvFileProvider) load() error {
	file, err := os.Open(p.filePath)
	if os.IsNotExist(err) {
		// File doesn't exist yet, that's OK
		return nil
	}
	if err != nil {
		return fmt.Errorf("failed to open env file: %w", err)
	}
	defer file.Close()

	scanner := bufio.NewScanner(file)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}

		parts := strings.SplitN(line, "=", 2)
		if len(parts) != 2 {
			continue
		}

		key := strings.TrimSpace(parts[0])
		value := strings.TrimSpace(parts[1])
		// Remove surrounding quotes
		value = strings.Trim(value, "\"'")

		p.secrets[key] = value
	}

	return scanner.Err()
}

func (p *EnvFileProvider) save() error {
	file, err := os.Create(p.filePath)
	if err != nil {
		return fmt.Errorf("failed to create env file: %w", err)
	}
	defer file.Close()

	// Write header
	fmt.Fprintf(file, "# Auto-generated by rotate-secrets\n")
	fmt.Fprintf(file, "# Generated at: %s\n\n", time.Now().UTC().Format(time.RFC3339))

	// Sort keys for consistent output
	keys := make([]string, 0, len(p.secrets))
	for k := range p.secrets {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	for _, key := range keys {
		fmt.Fprintf(file, "%s=%s\n", key, p.secrets[key])
	}

	return nil
}

func (p *EnvFileProvider) Name() string {
	return "env"
}

func (p *EnvFileProvider) Get(ctx context.Context, key string) (string, error) {
	value, exists := p.secrets[key]
	if !exists {
		return "", ErrSecretNotFound
	}
	return value, nil
}

func (p *EnvFileProvider) Set(ctx context.Context, key, value string) error {
	p.secrets[key] = value
	return p.save()
}

func (p *EnvFileProvider) Delete(ctx context.Context, key string) error {
	if _, exists := p.secrets[key]; !exists {
		return ErrSecretNotFound
	}
	delete(p.secrets, key)
	return p.save()
}

func (p *EnvFileProvider) List(ctx context.Context) ([]string, error) {
	keys := make([]string, 0, len(p.secrets))
	for k := range p.secrets {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys, nil
}

