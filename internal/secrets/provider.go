// Backup represents a secret backup entry.
type Backup struct {
	Key       string `json:"key"`
	Value     string `json:"value,omitempty"`
	ValueHash string `json:"value_hash,omitempty"`
	Encrypted bool   `json:"encrypted"`
	Timestamp string `json:"timestamp"`
	Warning   string `json:"warning,omitempty"`
}

// SaveBackup saves a backup to the specified directory.
func SaveBackup(backupDir, key, value string, encrypt bool) error {
	if err := os.MkdirAll(backupDir, 0700); err != nil {
		return fmt.Errorf("failed to create backup directory: %w", err)
	}

	timestamp := time.Now().UTC().Format("20060102_150405")
	filename := filepath.Join(backupDir, fmt.Sprintf("%s_%s.bak", key, timestamp))

	backup := Backup{
		Key:       key,
		Timestamp: timestamp,
		Encrypted: false,
	}

	// For security, only store hash unless encryption is enabled
	if encrypt {
		// Would use actual encryption here
		backup.Value = value
		backup.Encrypted = true
	} else {
		backup.ValueHash = hashValue(value)
		backup.Warning = "Value not stored - only hash available"
	}

	data, err := json.MarshalIndent(backup, "", "  ")
	if err != nil {
		return fmt.Errorf("failed to marshal backup: %w", err)
	}

	if err := os.WriteFile(filename, data, 0600); err != nil {
		return fmt.Errorf("failed to write backup file: %w", err)
	}

	return nil
}

func hashValue(value string) string {
	// Simple hash for demonstration
	// In production, use crypto/sha256
	hash := uint64(0)
	for _, c := range value {
		hash = hash*31 + uint64(c)
	}
	return fmt.Sprintf("%016x", hash)
}
